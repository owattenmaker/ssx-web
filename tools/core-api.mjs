// The course core's export reference (docs/core-api.md; docs/core-migration.md "Core API"): every function web/build-core.sh exports,
// its C signature and the comment above its definition, grouped by source file. A native front end calls the same functions.
//   node tools/core-api.mjs > docs/core-api.md      (node tools/core-api.mjs --check: exit 1 when the doc is not current)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const web = path.join(ROOT, 'web');

// the export list of web/build-core.sh
function exported() {
  const script = fs.readFileSync(path.join(web, 'build-core.sh'), 'utf8');
  const m = /EXPORTED_FUNCTIONS='(\[[^']*\])'/.exec(script);
  if (!m) throw new Error('web/build-core.sh: no EXPORTED_FUNCTIONS');
  return JSON.parse(m[1]).map((n) => n.slice(1));
}

// the definitions: EMSCRIPTEN_KEEPALIVE <ret> <name>(<params>), with the comment lines right above
function definitions() {
  const out = new Map();
  const files = fs
    .readdirSync(web)
    .filter((f) => f.endsWith('.cpp') || f.endsWith('.inc'))
    .sort();
  for (const f of files) {
    const text = fs.readFileSync(path.join(web, f), 'utf8');
    const re = /EMSCRIPTEN_KEEPALIVE\s+([^({;]*?)\b(\w+)\s*\(/g;
    let m;
    while ((m = re.exec(text))) {
      const name = m[2];
      if (out.has(name)) continue;
      let depth = 1;
      let i = m.index + m[0].length;
      for (; i < text.length && depth; i++) {
        if (text[i] === '(') depth++;
        else if (text[i] === ')') depth--;
      }
      const params = text
        .slice(m.index + m[0].length, i - 1)
        .replace(/\s+/g, ' ')
        .trim();
      const before = text.slice(0, m.index).split('\n');
      // the definition's own line may start with other code (one-line definitions): only whole comment lines above it count
      before.pop();
      const comment = [];
      while (before.length && /^\s*\/\//.test(before[before.length - 1])) comment.unshift(before.pop().replace(/^\s*\/\/\s?/, ''));
      out.set(name, { file: f, ret: m[1].replace(/\s+/g, ' ').trim(), params: params || 'void', comment: comment.join(' ') });
    }
  }
  return out;
}

function render() {
  const names = exported().filter((n) => n !== 'malloc' && n !== 'free');
  const defs = definitions();
  const byFile = new Map();
  const missing = [];
  for (const n of names) {
    const d = defs.get(n);
    if (!d) {
      missing.push(n);
      continue;
    }
    if (!byFile.has(d.file)) byFile.set(d.file, []);
    byFile.get(d.file).push({ name: n, ...d });
  }
  const lines = [
    '# Core API reference',
    '',
    'Generated by `node tools/core-api.mjs > docs/core-api.md` from web/build-core.sh\'s export list and the definitions in web/: do not',
    'edit by hand. The calls a front end makes, in order, are in [core-migration.md](core-migration.md) "Core API". Pointers are into',
    'the core\'s memory (wasm: HEAPU8 offsets; native: plain pointers); many returned pointers are the core\'s own static buffers, so',
    `copy what you keep before the next call. ${names.length} exports in ${byFile.size} files.`,
    ''
  ];
  for (const [file, rows] of [...byFile].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`## web/${file}`, '');
    for (const r of rows) {
      lines.push(`- \`${r.ret} ${r.name}(${r.params})\`${r.comment ? ': ' + r.comment.replace(/\|/g, '\\|') : ''}`);
    }
    lines.push('');
  }
  if (missing.length) lines.push('## Exported without an EMSCRIPTEN_KEEPALIVE definition in web/', '', ...missing.map((n) => `- \`${n}\``), '');
  return lines.join('\n');
}

const doc = render();
if (process.argv.includes('--check')) {
  const file = path.join(ROOT, 'docs/core-api.md');
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (current !== doc) {
    console.error('docs/core-api.md is not current: node tools/core-api.mjs > docs/core-api.md');
    process.exit(1);
  }
  process.exit(0);
}
process.stdout.write(doc);
