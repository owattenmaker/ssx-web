#!/bin/sh
set -eu
# The course core built natively (docs/core-migration.md "Native core"): clang, the host's architecture, the same sources as
# web/build-core.sh but web/rider_context.cpp / web/rider_tls.S (the wasm TLS swap), with native/core's rider contexts (the core's
# units compiled with -femulated-tls; native/core/rider_context_native.cpp gives every RIDER_LOCAL access the current context block),
# host hooks and the headless race driver. Two compiles at a time. NATIVE_OUT: the output folder (default local/native-core).
cd "$(dirname "$0")/.."
out=${NATIVE_OUT:-local/native-core}
mkdir -p "$out/obj"
CXX=${CXX:-clang++}
# the core's sources from web/build-core.sh's compile line, without the wasm-only context files
srcs=$(sed -n "$(grep -n '"$EMXX"' web/build-core.sh | head -1 | cut -d: -f1)p" web/build-core.sh | grep -o 'web/[a-z_/]*\.cpp\|engine/[a-z_/]*\.cpp' | grep -v 'web/rider_context.cpp')
srcs="$srcs native/core/host_hooks.cpp"
# MANAGER_SRC: another web/rider_manager.cpp (a scratch copy) in its place
if [ -n "${MANAGER_SRC:-}" ]; then srcs=$(echo "$srcs" | sed "s#web/rider_manager.cpp#$MANAGER_SRC#"); fi
flags="-std=c++20 -O2 -ffp-contract=off -fno-fast-math -include native/core/shim/native_shim.h -Inative/core/shim -Iengine -Iweb/third_party/nlohmann"
objs=""
running=0
for f in $srcs; do
  o="$out/obj/$(echo "$f" | tr '/' '_' | sed 's/\.cpp$/.o/')"
  # rebuild a unit when its source is newer than its object (headers: delete the folder)
  if [ ! -f "$o" ] || [ "$f" -nt "$o" ]; then
    $CXX $flags -femulated-tls -w -c "$f" -o "$o" &
    running=$((running + 1))
    if [ $running -ge 2 ]; then
      wait
      running=0
    fi
  fi
  objs="$objs $o"
done
wait
# the contexts themselves: ordinary storage (this file defines __emutls_get_address)
$CXX $flags -c native/core/rider_context_native.cpp -o "$out/obj/rider_context_native.o"
objs="$objs $out/obj/rider_context_native.o"
$CXX $flags -w -c native/core/race_driver.cpp -o "$out/obj/race_driver.o"
$CXX $objs "$out/obj/race_driver.o" -o "$out/race_driver"
echo "built $out/race_driver"
# CALLS=<a logged call stream (.jsonl)>: also the replayer of that stream (its export cases generated by native/gen_dispatch.py)
if [ -n "${CALLS:-}" ]; then
  python3 native/gen_dispatch.py "$CALLS" "$out/dispatch.inc"
  $CXX $flags -w -I"$out" -c native/core/replay_calls.cpp -o "$out/obj/replay_calls.o"
  $CXX $objs "$out/obj/replay_calls.o" -o "$out/replay_calls"
  echo "built $out/replay_calls"
fi
