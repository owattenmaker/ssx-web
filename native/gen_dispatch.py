#!/usr/bin/env python3
"""The native replayer's export table (docs/core-migration.md "Native core"): for every export a logged call stream uses, a C++
case that converts the logged JS arguments as the wasm call does (ToInt32 for integers, Math.fround for floats, a pointer resolved
by the replayer) and calls the native function. Signatures come from the core's sources (EMSCRIPTEN_KEEPALIVE definitions).

    gen_dispatch.py CALLS.jsonl OUT.inc
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def signatures():
    out = {}
    for path in list((ROOT / "web").glob("*.cpp")) + list((ROOT / "web").glob("*.inc")):
        text = path.read_text(errors="replace")
        for m in re.finditer(r"EMSCRIPTEN_KEEPALIVE\s+([^({;]*?)\b(\w+)\s*\(", text):
            ret, name = m.group(1).strip(), m.group(2)
            depth, i = 1, m.end()
            while i < len(text) and depth:
                depth += {"(": 1, ")": -1}.get(text[i], 0)
                i += 1
            params = text[m.end():i - 1].strip()
            if name not in out:
                out[name] = (ret, params)
    return out


def param_types(params):
    if not params or params == "void":
        return []
    types = []
    for p in params.split(","):
        p = p.strip()
        p = re.sub(r"\s*\b\w+$", "", p) if not p.endswith("*") else p
        types.append(p.strip())
    return types


def kind(t):
    if "*" in t:
        return "ptr"
    if t in ("float",):
        return "f32"
    if t in ("double",):
        return "f64"
    if t in ("uint32_t", "unsigned", "unsigned int"):
        return "u32"
    return "i32"


def main():
    calls, out = sys.argv[1], sys.argv[2]
    names = set()
    for line in open(calls):
        o = json.loads(line)
        if "n" in o and o["n"] not in ("_malloc", "_free"):
            names.add(o["n"][1:])
    sigs = signatures()
    lines = ["// generated by native/gen_dispatch.py: the export cases of one logged call stream", "extern \"C\" {"]
    for n in sorted(names):
        ret, params = sigs[n]
        lines.append(f"{ret} {n}({params});")
    lines.append("}")
    lines.append("static bool dispatch(const std::string& name, Args& a, Result& r) {")
    for n in sorted(names):
        ret, params = sigs[n]
        types = param_types(params)
        conv = []
        for k, t in enumerate(types):
            kd = kind(t)
            if kd == "ptr":
                conv.append(f"reinterpret_cast<{t}>(a.ptr({k}))")
            elif kd == "f32":
                conv.append(f"a.f32({k})")
            elif kd == "f64":
                conv.append(f"a.f64({k})")
            elif kd == "u32":
                conv.append(f"uint32_t(a.i32({k}))")
            else:
                conv.append(f"({t})a.i32({k})")
        call = f"{n}({', '.join(conv)})"
        if ret == "void":
            body = f"{call}; r.set();"
        elif "*" in ret:
            body = f"r.setPtr((const void*){call});"
        else:
            body = f"r.setNumber(double({call}));"
        lines.append(f"    if (name == \"_{n}\") {{ {body} return true; }}")
    lines.append("    return false;")
    lines.append("}")
    Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
